#!/usr/bin/env python3
"""Bake shared collision from the Sanctuary layout. Run after editing wall cells, roofs, doors or landmarks."""
import json
import sys
from collections import deque
from pathlib import Path
root = Path(__file__).resolve().parents[1]
data = json.loads((root / 'client/data/world/sanctuary/layout.json').read_text())
ids = [b['id'] for b in data['buildings']]
assert len(ids) == len(set(ids)), 'Building IDs must remain unique'
wall_cells = {tuple(p) for p in data['walls']}
roof_owners = {}
for building in data['buildings']:
    floor = {tuple(p) for p in building['floors']}
    roof = {tuple(p) for p in building['roof_cells']}
    assert floor <= roof, f"{building['id']} floor lies outside its roof group"
    assert not floor & wall_cells, f"{building['id']} has a wall on its floor"
    assert tuple(building['entrance']) in floor, f"{building['id']} entrance is blocked"
    for cell in roof:
        assert cell not in roof_owners, f"Overlapping roof ownership at {cell}"
        roof_owners[cell] = building['id']

def inside(x, y):
    polygon = data['land_polygon']
    hit = False
    for a, b in zip(polygon, polygon[1:] + polygon[:1]):
        if (a[1] > y) != (b[1] > y) and x < (b[0]-a[0])*(y-a[1])/(b[1]-a[1])+a[0]:
            hit = not hit
    return hit

solids = []
for y in range(-96, 96):
    start = None
    for x in range(-104, 105):
        solid = x < 104 and not inside(x + .5, y + .5)
        if solid and start is None:
            start = x
        if not solid and start is not None:
            width = x - start
            previous = next((r for r in reversed(solids)
                             if r[0] == start and r[2] == width and r[1]+r[3] == y), None)
            if previous is None:
                solids.append([start, y, width, 1])
            else:
                previous[3] += 1
            start = None
# Merge contiguous wall cells into horizontal spans. Both rendering and collision
# consume the exact same cells; interiors and door thresholds are never filled.
walls = {tuple(p) for p in data['walls']}
for y in sorted({p[1] for p in walls}):
    xs = sorted(x for x, row in walls if row == y)
    start = previous = xs[0]
    for x in xs[1:] + [xs[-1] + 2]:
        if x != previous + 1:
            solids.append([start, y, previous - start + 1, 1])
            start = x
        previous = x
solids += data['gate_rects']
text = '// Generated by scripts/bake_sanctuary.py; do not edit.\nuse crate::rect::Rect;\npub const SOLIDS: &[Rect] = &[\n'
for r in solids:
    text += '    Rect::new(' + ', '.join(f'{v * data["tile_size"]:.1f}' for v in r) + '),\n'
text += '];\n'
def vectors(name, points):
    return f'pub const {name}: [crate::Vec2; {len(points)}] = [\n' + ''.join(
        f'    crate::Vec2::new({x*32+16:.1f}, {y*32+16:.1f}),\n' for x,y in points) + '];\n'
text += vectors('SPAWNS', data['spawn_points'])
text += '#[cfg(test)]\n' + vectors('GATES', data['gates'])
text += '#[cfg(test)]\n' + vectors('SERVICES', [data[k] for k in ['spawn', 'arena', 'bank', 'vendor', 'priest']])
text += '#[cfg(test)]\n' + vectors('ROOM_ANCHORS', [b['interior_anchor'] for b in data['buildings']])
# Player-radius clearance and connectivity protect all required service routes.
def free(p):
    x, y = p[0]+.5, p[1]+.5
    return -104 < x < 104 and -96 < y < 96 and not any(
        a-.5 <= x < a+w+.5 and b-.5 <= y < b+h+.5 for a, b, w, h in solids)
start = tuple(data['spawn'])
assert free(start), 'Arrival is blocked'
seen = {start}
queue = deque([start])
while queue:
    x, y = queue.popleft()
    for p in [(x-1,y), (x+1,y), (x,y-1), (x,y+1)]:
        if p not in seen and free(p):
            seen.add(p)
            queue.append(p)
for key in ['arena', 'bank', 'vendor', 'priest']:
    assert tuple(data[key]) in seen, f'{key} is unreachable with player clearance'
for building in data['buildings']:
    assert tuple(building['interior_anchor']) in seen, f"{building['id']} is unreachable"
    entrance, street = tuple(building['entrance']), tuple(building['street'])
    assert free(street), f"{building['id']} street approach is obstructed"
    assert free(entrance), f"{building['id']} doorway lacks player clearance"
    assert street in seen, f"{building['id']} approach is unreachable"
    assert street not in roof_owners, f"{building['id']} street approach hides a roof"
    assert abs(entrance[0]-street[0])+abs(entrance[1]-street[1]) == 1
    # An anchor reachable through some other hole is insufficient: the marked
    # entrance must lead to the interior without leaving its ownership group.
    roof = {tuple(p) for p in building['roof_cells']}
    reached = {entrance}
    queue = deque([entrance])
    while queue:
        x, y = queue.popleft()
        for step in [(x-1,y), (x+1,y), (x,y-1), (x,y+1)]:
            if step in roof and step not in reached and free(step):
                reached.add(step)
                queue.append(step)
    assert tuple(building['interior_anchor']) in reached, f"{building['id']} marked entrance misses its interior"
for spawn in data['spawn_points']:
    assert tuple(spawn) in seen, 'Spawn anchor is blocked'
for gate in data['gates']:
    assert not free(gate), 'Future exit is unsealed'
target = root / 'rust/sim_core/src/sanctuary.rs'
if '--check' in sys.argv:
    assert target.read_text() == text, 'Collision bake is stale; run scripts/bake_sanctuary.py'
else:
    target.write_text(text)
print(f'Sanctuary: {len(solids)} collision rectangles; all services reachable; four exits blocked')
