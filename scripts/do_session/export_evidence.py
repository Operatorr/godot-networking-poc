def _timeline(sim):
    t0 = session_clock.parse(sim.stack.registry.status(sim.session_id)['t0_utc'])
    rows = []
    for event in sim.stack.registry.journal(sim.session_id):
        if event['kind'] in TIMELINE_KINDS:
            data = event.get('data') or {}
            rows.append(dict(t_s=round(session_clock.parse(event['at']) - t0, 3), kind=event['kind'], **{key: data[key] for key in ('run_id', 'outcome', 'status', 'reason', 'first_failure', 'deadline') if key in data}))
    return rows


def _gets(sim):
    return sum(1 for command in sim.guests.commands if command.get('step') == 'get')


def _row(sim, extra=None):
    """What one session did and how it ended, with nothing machine-specific. The inventory's hashes stay out of it: its bytes hold scripted times, but its paths are the session's."""
    status = sim.stack.registry.status(sim.session_id)
    export_root = sim.root / se.EXPORT_DIR
    generations = sorted(path.name for path in export_root.glob('gen-*') if path.is_dir() and '.writing-' not in path.name) if export_root.exists() else []
    latest = {}
    report = {}
    if generations:
        latest = sim.document(generations[-1])
        if (sim.generation(generations[-1]) / se.REPORT_JSON).exists():
            report = sim.document(generations[-1], se.REPORT_JSON)
    results = report.get('results') or {}
    claim = (results.get('measurement') or {}).get('claim') or {}
    t0 = session_clock.parse(status['t0_utc'])
    row = dict(outcomes=[list(item) for item in sim.outcomes()], search_status=(results.get('measurement') or {}).get('search_status'), claim_kind=claim.get('kind'), claim_players=claim.get('players'), claim_confirmed=claim.get('confirmed'), establishes=report.get('establishes'),
               history_withheld=bool((results.get('measurement') or {}).get('journal_claim_withheld')), evidence_registry=status['evidence']['status'], evidence_latest_export=latest.get('status'), evidence_problems=latest.get('problems'), overall=status['overall'], cleanup_requested=status['cleanup']['requested_at'] is not None, cleanup_verified=status['cleanup']['verified_at'] is not None,
               overdue=status['cleanup']['overdue'], overrun_s=status['cleanup']['overrun_s'], generations=generations, roles={'%s/%s' % (item['run_id'].split('-', 4)[-1], item['role']): item['status'] for item in latest.get('roles') or ()}, required_absent=sorted({name for item in latest.get('roles') or () for name in item.get('required_absent') or ()}),
               attempts_retained=latest.get('attempts_retained'), corrupt_retained=len(latest.get('corrupt_files') or ()), transfers=_gets(sim), recovery_deadline_s=round(session_clock.parse(status['recovery_deadline_utc']) - t0, 3) if status['recovery_deadline_utc'] else None, resources=[dict(kind=item['kind'], status=item['status'], attempts=item['attempts']) for item in status['resources']], incidents=[dict(kind=item['kind'], status=item['status']) for item in status['incidents']],
               reproduces=(not se.reproduce(sim.root, generations[-1])) if generations else None, publication=ep.publication_status(sim.root)['status'], published_text=bool(generations) and (sim.generation(generations[-1]) / se.PUBLISHED).exists(), timeline=_timeline(sim))
    row.update(controller_inputs_missing=(latest.get('controller_inputs') or {}).get('missing'), controller_inputs_corrupt=(latest.get('controller_inputs') or {}).get('corrupt'), not_inventoried=latest.get('not_inventoried'), publication_detail=ep.publication_status(sim.root)['publication']['status'])
    row.update(extra or {})
    return row


