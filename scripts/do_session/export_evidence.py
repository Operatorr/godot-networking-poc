    (directory / ep.CANONICAL_ROOT).mkdir(parents=True)
    now = '2026-11-05T00:00:00+00:00'
    statuses = []
    ep.publish(sim.root, 'gen-0001', [ep.RepositoryDocs(directory / ep.CANONICAL_ROOT)], now)
    statuses.append(ep.publication_status(sim.root)['status'])
    summary = (sim.generation('gen-0001') / 'published' / 'summary.md').read_bytes()
    reference = 'https://repository.invalid/tree/%s/%s/%s/%s/gen-0001' % ('0' * 40, ep.CANONICAL_ROOT, ep.SESSIONS_DIR, sim.session_id)
    ep.record_publication(sim.root, 'gen-0001', reference, now, ep.sha256_bytes(summary), 'scenario operator')
    statuses.append(ep.publication_status(sim.root)['status'])
    publisher = Publisher()
    ep.publish(sim.root, 'gen-0001', [publisher], now)
    statuses.append(ep.publication_status(sim.root)['status'])
    return sim, dict(status_after_each_step=statuses, adapter_received=sorted(publisher.files))


