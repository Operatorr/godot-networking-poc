def scenarios():
    rows = {}
    for name, play in SCENARIOS:
        case = _Case()
        try:
            sim, extra = play(case)
            rows[name] = _row(sim, extra)
        finally:
            case.doCleanups()
    return rows


def sample(out):
    """One session's published text exactly as an export writes it, under a banner, so nobody can take its fixture numbers for an observation. Its hash inventory stays, because it is the format: every line is a hash of a deleted fixture file."""
    case = _Case()
    try:
        sim = ef.ExportSim(case, ef.enriched(ef.CONFIRMING))
        sim.batch()
        sim.drive_cleanup()
        exported = _late_export(sim)
        source = sim.generation(exported.generation) / se.PUBLISHED
        target = pathlib.Path(out) / 'synthetic-sample'
        target.mkdir(parents=True, exist_ok=True)
        (target / 'summary.md').write_text(SAMPLE_BANNER + (source / 'summary.md').read_text())
        summary = json.loads((source / 'summary.json').read_text())
        (target / 'summary.json').write_text(sr.canonical(dict(synthetic_fixture=NOTE, **summary)))
        (target / 'SHA256SUMS').write_bytes((source / 'SHA256SUMS').read_bytes())
    finally:
        case.doCleanups()


def write_sums(out):
    out = pathlib.Path(out)
    names = sorted(str(path.relative_to(out)) for path in out.rglob('*') if path.is_file() and path.name != 'README.md' and path.relative_to(out).as_posix() != 'SHA256SUMS')
    (out / 'SHA256SUMS').write_text(''.join('%s  %s\n' % (hashlib.sha256((out / name).read_bytes()).hexdigest(), name) for name in names))


def generate(out):
    out = pathlib.Path(out)
    out.mkdir(parents=True, exist_ok=True)
    rows = scenarios()
    document = dict(schema=SCHEMA, kind='synthetic', note=NOTE, scenarios=rows)
    (out / 'synthetic-exports.json').write_text(json.dumps(document, indent=1, sort_keys=True) + '\n')
    sample(out)
    write_sums(out)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--out', required=True)
    args = parser.parse_args(argv)
    generate(args.out)
    return 0


