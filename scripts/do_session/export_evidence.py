def play_publication_needs_more_than_a_local_copy(case):
    class Publisher:
        name = ep.PUBLICATION_NAME
        publishes = True

        def __init__(self):
            self.files = {}

        def reference(self, session_id, generation):
            return 'https://publication-adapter.invalid/%s/%s' % (session_id, generation)

        def put(self, session_id, generation, files):
            self.files.update(files)

        def read_back(self, session_id, generation, name):
            return self.files[name]
    sim = ef.ExportSim(case, ef.enriched(ef.CONFIRMING))
    sim.batch()
    sim.drive_cleanup()
    directory = pathlib.Path(tempfile.mkdtemp(prefix='omega-export-evidence-'))
