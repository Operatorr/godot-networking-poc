def _first_failure_scenario(case, then):
    """The first game copy fails and stays failing. Returns the sim and a list holding that first failure's time and file."""
    sim = ef.ExportSim(case, ef.enriched(ef.CONFIRMING))
    sim.ready()
    first = []

    def hook(role, run_id, relative, data, attempt):
        if role == 'game' and not first:
            first.append((sim.clock.wall(), relative))
            return 1, b'cut'
        if first and (role, relative) == ('game', first[0][1]):
            return 1, b'cut'
        return then(sim, role, relative, data)
    sim.guests.get_hook = hook
    return sim, first


